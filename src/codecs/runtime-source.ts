const JSON_TAIL = String.raw`
export interface JsonCodec<T> {
  readonly modelId: string;
  readonly format: "json";
  /** Reads an already parsed JSON tree. */
  decode(input: unknown): T;
  /** Produces the JSON tree; keys follow the declared mapping order. */
  encode(value: T): unknown;
  /** Parses JSON text, then decodes it. */
  parse(text: string): T;
  /** Compact JSON text of encode(value). */
  stringify(value: T): string;
}

export function jsonCodec<T>(
  modelId: string,
  decodeTree: (input: unknown) => T,
  encodeTree: (value: T) => unknown,
): JsonCodec<T> {
  const decode = (input: unknown): T => run(modelId, () => decodeTree(input));
  const encode = (value: T): unknown => run(modelId, () => encodeTree(value));
  return {
    modelId,
    format: "json",
    decode,
    encode,
    parse(text) {
      let tree: unknown;
      try {
        tree = JSON.parse(text) as unknown;
      } catch (error) {
        throw new LmlError({
          reason: "invalid_document",
          model_id: modelId,
          format: "json",
          location: "/input",
          detail: error instanceof Error ? error.message : "invalid JSON",
        });
      }
      return decode(tree);
    },
    stringify(value) {
      return JSON.stringify(encode(value));
    },
  };
}
`;

const YAML_TAIL = String.raw`
/** The two functions of a YAML library; supplied by the caller, never imported. */
export interface YamlLibrary {
  parse(text: string): unknown;
  stringify(value: unknown): string;
}

export interface YamlCodec<T> {
  readonly modelId: string;
  readonly format: "yaml";
  /** Reads an already parsed YAML tree (plain data: no classes, no aliases). */
  decode(input: unknown): T;
  /** Produces the YAML tree; keys follow the declared mapping order. */
  encode(value: T): unknown;
  /** Parses YAML text with the given library, then decodes it. */
  parse(text: string, yaml: YamlLibrary): T;
  /** YAML text of encode(value) with the given library. */
  stringify(value: T, yaml: YamlLibrary): string;
}

export function yamlCodec<T>(
  modelId: string,
  decodeTree: (input: unknown) => T,
  encodeTree: (value: T) => unknown,
): YamlCodec<T> {
  const decode = (input: unknown): T => run(modelId, () => decodeTree(input));
  const encode = (value: T): unknown => run(modelId, () => encodeTree(value));
  return {
    modelId,
    format: "yaml",
    decode,
    encode,
    parse(text, yaml) {
      let tree: unknown;
      try {
        tree = yaml.parse(text);
      } catch (error) {
        throw new LmlError({
          reason: "invalid_document",
          model_id: modelId,
          format: "yaml",
          location: "/input",
          detail: error instanceof Error ? error.message : "invalid YAML",
        });
      }
      return decode(tree);
    },
    stringify(value, yaml) {
      return yaml.stringify(encode(value));
    },
  };
}
`;
