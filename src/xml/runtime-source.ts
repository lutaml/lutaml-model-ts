const UNPAIRED_SURROGATE = /[\uD800-\uDBFF](?![\uDC00-\uDFFF])|(?<![\uD800-\uDBFF])[\uDC00-\uDFFF]/;
const INTEGER_LEXICAL = /^[+-]?[0-9]+$/;

const FLOAT_WIRE = /^-?[0-9]+\.[0-9]+(?:e-?[0-9]+)?$/;

/** Ruby-compatible shortest round-trip spelling: lowercase e, no +, no leading zeros, fraction digit always. */
function floatText(value: number): string {
  if (value === 0) return Object.is(value, -0) ? "-0.0" : "0.0";
  const [mantissa = "", exp = "0"] = Math.abs(value).toExponential().split("e");
  const digits = mantissa.replace(".", "");
  const decpt = Number(exp) + 1;
  const sign = value < 0 ? "-" : "";
  if (decpt > -4 && decpt <= 15) {
    if (decpt <= 0) return sign + "0." + "0".repeat(-decpt) + digits;
    if (decpt >= digits.length) return sign + digits + "0".repeat(decpt - digits.length) + ".0";
    return sign + digits.slice(0, decpt) + "." + digits.slice(decpt);
  }
  return sign + digits[0] + "." + (digits.length > 1 ? digits.slice(1) : "0") + "e" + (decpt - 1);
}

export function dStr(s: string): string {
  return UNPAIRED_SURROGATE.test(s) ? xmlFail("string is not valid Unicode") : s;
}

export function dBool(s: string): boolean {
  const t = s.trim();
  if (t === "true" || t === "1") return true;
  if (t === "false" || t === "0") return false;
  return xmlFail("expected true, false, 1 or 0");
}

export function dInt(s: string): bigint {
  const t = s.trim();
  return INTEGER_LEXICAL.test(t) ? BigInt(t) : xmlFail("expected an exact integer");
}

export function dFloat(s: string): number {
  const t = s.trim();
  if (!FLOAT_WIRE.test(t)) return xmlFail("expected a canonical float");
  const n = Number(t);
  return Number.isFinite(n) && floatText(n) === t ? n : xmlFail("float is not in canonical form");
}

export function dBound<T>(s: string, parse: (lexical: string) => T): T {
  try {
    return parse(s);
  } catch (error) {
    if (error instanceof LmlError) throw new XmlError(error.info.reason, error.info.detail ?? error.info.reason);
    return xmlFail(error instanceof Error ? error.message : "unparseable value");
  }
}

export interface QName {
  readonly namespace: string | null;
  readonly local: string;
}

export function dQName(s: string, el: El): QName {
  const t = s.trim();
  const colon = t.indexOf(":");
  const prefix = colon < 0 ? "" : t.slice(0, colon);
  const local = colon < 0 ? t : t.slice(colon + 1);
  if (local === "" || local.includes(":")) return xmlFail("expected a QName");
  const uri = inScope(el, prefix);
  if (uri === undefined) {
    return prefix === "" ? { namespace: null, local } : xmlFail("QName prefix " + prefix + " is not bound");
  }
  return { namespace: uri === "" ? null : uri, local };
}

const B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
const B64_SHAPE = /^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/;

export function dBase64(s: string): Uint8Array {
  const v = s.replace(/\s+/g, "");
  if (!B64_SHAPE.test(v)) return xmlFail("expected base64");
  const pad = v.endsWith("==") ? 2 : v.endsWith("=") ? 1 : 0;
  const out = new Uint8Array((v.length / 4) * 3 - pad);
  let n = 0;
  for (let i = 0; i < v.length; i += 4) {
    const a = B64.indexOf(v.charAt(i));
    const b = B64.indexOf(v.charAt(i + 1));
    const c = v.charAt(i + 2) === "=" ? 0 : B64.indexOf(v.charAt(i + 2));
    const d = v.charAt(i + 3) === "=" ? 0 : B64.indexOf(v.charAt(i + 3));
    const word = (a << 18) | (b << 12) | (c << 6) | d;
    if (n < out.length) out[n++] = (word >> 16) & 255;
    if (n < out.length) out[n++] = (word >> 8) & 255;
    if (n < out.length) out[n++] = word & 255;
  }
  return out;
}

export function dHex(s: string): Uint8Array {
  const v = s.trim();
  if (!/^(?:[0-9a-fA-F]{2})*$/.test(v)) return xmlFail("expected hex");
  const out = new Uint8Array(v.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(v.slice(i * 2, i * 2 + 2), 16);
  return out;
}

