/**
 * Source text of the generated `xml/runtime.ts`: small fixed readers/writers
 * over the public moxml-ts faces, shared by every generated XML codec. It is
 * static code, not a model interpreter: generated code passes literal rule
 * tables and closures, never schema-provided code. Written with String.raw;
 * the only placeholder is the contracts module.
 *
 * Faces used (moxml-ts, fix/codec-faces): Node.qualifiedName/localName/
 * namespaceUri/inScopeNamespaces/attributes, Document.createElementNS/
 * createText/setRoot, Node.setAttributeNS/declareNamespace/addChild. CDATA
 * text is read with Document.xpath on a position path.
 */
export function xmlRuntimeSource(contractsModule: string): string {
  return HEAD.replaceAll("@@CONTRACTS@@", JSON.stringify(contractsModule)) + READER + WRITER;
}

